/**
 * Encrypts the market data CSVs into src/server/generated/marketDataSealed.ts
 * so a host without the files (Netlify) can ship them inside the server
 * bundle without the listings being readable in this public repo.
 *
 *   MARKET_DATA_KEY=<base64 32 bytes> MARKET_DATA_DIR=/path/to/market-data npm run market:seal
 *
 * Make a key once with: node -e "console.log(require('crypto').randomBytes(32).toString('base64'))"
 * and set the same MARKET_DATA_KEY on the server (Netlify env var, Functions scope).
 */
import fs from 'fs';
import path from 'path';
import { sealMarketFiles } from '../src/server/marketDataSeal.ts';

const dir = path.resolve(process.argv[2] || process.env.MARKET_DATA_DIR || 'data/market');
const key = process.env.MARKET_DATA_KEY;
if (!key) throw new Error('Set MARKET_DATA_KEY (base64, 32 bytes).');

function pickListings(): string {
  const all = path.join(dir, 'listings_all.csv');
  if (fs.existsSync(all)) return all;
  const monthly = fs.readdirSync(dir).filter((f) => /^uk_dental_listings_.*\.csv$/.test(f)).sort();
  if (!monthly.length) throw new Error(`No listings_all.csv or uk_dental_listings_*.csv in ${dir}`);
  return path.join(dir, monthly[monthly.length - 1]);
}

const files = {
  'listings_all.csv': fs.readFileSync(pickListings(), 'utf8'),
  'market_index.csv': fs.readFileSync(path.join(dir, 'market_index.csv'), 'utf8'),
};
const sealed = sealMarketFiles(files, key);
const out = path.resolve('src/server/generated/marketDataSealed.ts');
fs.writeFileSync(
  out,
  `// Generated by \`npm run market:seal\` on ${new Date().toISOString().slice(0, 10)}. Do not edit.\n` +
    `// AES-256-GCM ciphertext of the market data CSVs; unreadable without MARKET_DATA_KEY.\n` +
    `export const SEALED_MARKET_DATA = ${JSON.stringify(sealed)};\n`,
);
console.log(`Wrote ${out} (${Math.round(sealed.length / 1024)} KB)`);
